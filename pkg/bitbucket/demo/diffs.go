// unifiedDiff joins the lines of a diff and terminates the text with a newline,
// the way git writes one. The fixtures are written line by line because a raw
// string literal cannot hold the tab indentation the Go samples need.
func unifiedDiff(lines ...string) string {
	return strings.Join(lines, "\n") + "\n"
}

